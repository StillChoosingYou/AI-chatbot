def init_schema(connection):
    """Create the tables that do not exist yet. Safe on every start and from several processes at once."""
    connection.execute('SELECT pg_advisory_xact_lock(%s)', (SCHEMA_LOCK,))
    for statement in (*SCHEMA, *UPGRADES):
        connection.execute(statement)


def seed_demo_records(connection):
    """Add the six fictional demo students when the inventory is empty. True if it added them."""
    if connection.execute('SELECT 1 FROM inventory LIMIT 1').fetchone():
        return False
    connection.executemany(
        f'INSERT INTO inventory ({DEMO_COLUMNS},token) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)',
        [(*row, secrets.token_urlsafe(18)) for row in DEMO_RECORDS])
    return True


def only_untouched_demo_data(connection):
    """True when the database holds just the demo students exactly as seeded (by this version or an
    earlier one), and nothing else."""
    for table in TABLES[1:]:
        if connection.execute(f'SELECT 1 FROM {table} LIMIT 1').fetchone():
            return False
    rows = connection.execute(
        f"SELECT {DEMO_COLUMNS} FROM inventory "
        "WHERE schedule_type = '' AND schedule_date = '' AND schedule_time = '' AND notes = ''").fetchall()
    found = sorted(tuple(row) for row in rows)
    return found in (sorted(DEMO_RECORDS), sorted(LEGACY_DEMO_RECORDS))
