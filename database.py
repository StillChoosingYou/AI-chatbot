"""PostgreSQL access for the school ID app: a small connection pool and the table definitions.

The rest of the app keeps a familiar shape. `with connect() as db:` gives a connection whose
`db.execute(sql, params)` returns a cursor. The block commits when it ends normally and rolls back
when it raises. Rows work like sqlite3.Row did: row[0], row['name'] and dict(row).
Placeholders are %s (write %% for a literal percent sign inside SQL text).
"""
import hashlib
import os
import secrets
from contextlib import contextmanager

import psycopg
from psycopg_pool import ConnectionPool

SCHEMA_LOCK = 7041985   # any constant: makes several server processes set up the tables one at a time


class Row(tuple):
    """A result row that behaves like sqlite3.Row: row[0], row['name'] and dict(row) all work."""

    def __new__(cls, names, values):
        row = super().__new__(cls, values)
        row._names = names
        return row

    def __getitem__(self, key):
        if isinstance(key, str):
            try:
                return tuple.__getitem__(self, self._names.index(key))
            except ValueError:
                raise KeyError(key) from None
        return tuple.__getitem__(self, key)

    def keys(self):
        return list(self._names)


def row_factory(cursor):
    names = [column.name for column in cursor.description or ()]
    return lambda values: Row(names, values)


class AppConnection(psycopg.Connection):
    def executemany(self, sql, rows):
        with self.cursor() as cursor:
            cursor.executemany(sql, rows)


class Database:
    """One connection pool per application. Close it when the app is done (tests, scripts)."""

    def __init__(self, conninfo, max_size=None):
        try:                                   # a clear message beats "pool initialisation incomplete"
            with psycopg.connect(conninfo, connect_timeout=10):
                pass
        except psycopg.OperationalError as error:
            raise RuntimeError(f'Cannot connect to PostgreSQL: {str(error).strip()}') from None
        self.pool = ConnectionPool(
            conninfo, connection_class=AppConnection, min_size=1,
            max_size=max_size or int(os.environ.get('DATABASE_POOL_SIZE', '10')), open=False,
            # prepare_threshold=None keeps this working behind PgBouncer / Supabase's pooler.
            kwargs={'row_factory': row_factory, 'prepare_threshold': None, 'connect_timeout': 10},
            timeout=5, name='school-id')
        self.pool.open(wait=True, timeout=15)

    def _working_connection(self):
        """A pooled connection that answers. Dead ones (database restarted, idle timeout, killed by an
        admin) are thrown away at once. The pool's own `check=` option would sleep 1 s, 2 s, 4 s ...
        between throwing away dead connections, which is far too slow after a database restart."""
        for _ in range(self.pool.max_size + 1):
            connection = self.pool.getconn()
            try:
                ConnectionPool.check_connection(connection)
                return connection
            except psycopg.Error:
                self.pool.putconn(connection)          # a broken connection is dropped and replaced
        raise psycopg.OperationalError('the database stopped answering')

    @contextmanager
    def connect(self):
        """Commits when the block ends normally, rolls back when it raises, and always returns the connection."""
        connection = self._working_connection()
        try:
            with connection:
                yield connection
        finally:
            self.pool.putconn(connection)

    def close(self):
        self.pool.close()


def student_lock_key(student_id):
    """Advisory-lock number for one student ID, whatever its letter case."""
    digest = hashlib.blake2b(student_id.lower().encode('utf-8'), digest_size=8).digest()
    return int.from_bytes(digest, 'big', signed=True)


def lock_student(connection, student_id):
    """Wait for any other transaction that is creating or accepting a record for this student ID.

    Held until the transaction ends. Without it, two requests for a new student could both see
    "no record yet" and both try to create one.
    """
    connection.execute('SELECT pg_advisory_xact_lock(%s)', (student_lock_key(student_id),))


