"""Local ANN inference, shared by the trainer and Flask chatbot."""
import hashlib
from pathlib import Path

import joblib
import numpy as np
import sklearn

ROOT = Path(__file__).resolve().parent
DEFAULT_MODEL = ROOT / 'data' / 'intent_model.joblib'
DEFAULT_THRESHOLD = 0.35


def file_hash(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def classify(pipeline, messages, threshold=DEFAULT_THRESHOLD):
    """Reject empty-vocabulary or low-confidence input; scores are uncalibrated."""
    vectors = pipeline.named_steps['tfidf'].transform(messages)
    network = pipeline.named_steps['ann']
    probabilities = network.predict_proba(vectors)
    labels = network.classes_[np.argmax(probabilities, axis=1)].astype(object)
    confidence = np.max(probabilities, axis=1)
    for index in range(len(labels)):
        if vectors[index].nnz == 0 or confidence[index] < threshold:
            labels[index] = 'out_of_scope'
    return labels, confidence


class ANNIntentModel:
    def __init__(self, model_path=DEFAULT_MODEL):
        model_path = Path(model_path)
        if not model_path.is_file():
            raise RuntimeError('ANN model is missing. Run: python train_model.py')
        # Load only an artifact generated by your own local training script.
        bundle = joblib.load(model_path)
        if bundle.get('format_version') != 1 or bundle.get('sklearn_version') != sklearn.__version__:
            raise RuntimeError('ANN model version differs from this installation. Run: python train_model.py')
        for name, expected in bundle['input_hashes'].items():
            if file_hash(ROOT / name) != expected:
                raise RuntimeError(f'{name} changed since training. Run: python train_model.py')
        self.pipeline = bundle['pipeline']
        self.threshold = bundle['threshold']

    def match(self, text):
        labels, _ = classify(self.pipeline, [text], self.threshold)
        return str(labels[0])
